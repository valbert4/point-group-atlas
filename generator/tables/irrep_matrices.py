"""Unitary matrices of every irrep of a finite group (CONVENTIONS.md section 9), in the row-vector
convention of the elements block: D(g) D(h) = D(gh) with gh read from multiplication_table.

Constructions, in this order:
  linear          a 1-dimensional irrep: D(g) = [chi(g)];
  axial-monomial  an axial group: D^(k,a)(g) = s^a diag(conj w^k, w^k) when the planar block
                  A(g) is a rotation and s^a [[0, w^k], [conj w^k, 0]] when it is a reflection,
                  w = P11 + i P12, s = P33,
                  on the basis {(x-iy)^k z^a, (x+iy)^k z^a}; (k, a) the first pair, k = 1, 2, ...,
                  a = 0, 1, whose character is the irrep's;
  defining        the irrep whose character is that of the 3x3 matrices P(g);
  twist           D^j (x) lambda for an irrep j already built and a 1-dimensional lambda;
  galois          D^j with sigma_t: zeta_M -> zeta_M^t applied to every entry;
  perm-dft        the permutation action of G on the right cosets of a subgroup of index d + 1
                  whose fixed-point count is chi + 1, on the sum-zero subspace in the Fourier
                  basis f_k = sum_j zeta_(d+1)^(-jk) e_j, where g acts on the vector e_j of coset
                  j as on functions: g e_j' = e_j, j' the coset that contains xi_j g.
"""
from fractions import Fraction as F
from math import gcd

from ..exact.cyclo import Cyc, csum

MAX_PERM_INDEX = 12


def scale(A, c):
    return [[c * x for x in row] for row in A]


def trace(A):
    return csum([A[i][i] for i in range(len(A))])


def lift(x, M):
    """x as an element of Q(zeta_lcm(M, x.M))."""
    return x * Cyc.zeta(M, 0)


class Ctx:
    """The group of a record: elements, multiplication table, matrices P(g), classes and
    characters."""

    def __init__(self, doc):
        el = doc["elements"]
        self.items = el["items"]
        self.n = el["count"]
        self.mt = el["multiplication_table"]
        self.e = el["identity_index"]
        self.P = [[[Cyc.from_json(v) for v in row] for row in it["matrix"]] for it in self.items]
        ct = doc["character_table"]
        self.classes = [c["id"] for c in ct["classes"]]
        cpos = {c: j for j, c in enumerate(self.classes)}
        self.cls_of = [cpos[it["class_id"]] for it in self.items]
        self.irreps = ct["irreps"]
        self.chi = [[Cyc.from_json(v) for v in ir["chi"]] for ir in self.irreps]

    def chi_el(self, i, g):
        return self.chi[i][self.cls_of[g]]

    def char_of(self, mats):
        """The character of the matrices as a row over the classes, or None when the traces are
        not constant on the classes."""
        row = [None] * len(self.classes)
        for g in range(self.n):
            t = trace(mats[g])
            c = self.cls_of[g]
            if row[c] is None:
                row[c] = t
            elif row[c] != t:
                return None
        return row

    def match(self, mats):
        """The index of the irrep whose character the matrices have, or None."""
        row = self.char_of(mats)
        if row is None:
            return None
        for i, r in enumerate(self.chi):
            if all(r[c] == row[c] for c in range(len(r))):
                return i
        return None


def build_linear(ctx, i):
    return [[[ctx.chi_el(i, g)]] for g in range(ctx.n)]


def axial_blocks(ctx):
    """(w, proper, s) per element, w = P11 + i P12, s = P33, or None when some P(g) does not
    preserve the z axis."""
    out = []
    for g in range(ctx.n):
        P = ctx.P[g]
        if not (P[0][2].is_zero() and P[1][2].is_zero()
                and P[2][0].is_zero() and P[2][1].is_zero()):
            return None
        s = P[2][2]
        a, b, c, d = P[0][0], P[0][1], P[1][0], P[1][1]
        eps = a * d - b * c
        out.append((a + Cyc.zeta(4, 1) * b, eps == Cyc.one(), s))
    return out


def axial_2d(blocks, k, a):
    """D^(k,a) of the module docstring."""
    Z = Cyc.zero()
    mats = []
    for (z, proper, s) in blocks:
        zk = Cyc.one()
        for _ in range(k):
            zk = zk * z
        w = zk.conjugate()
        D = [[w, Z], [Z, zk]] if proper else [[Z, zk], [w, Z]]
        if a:
            D = scale(D, s)
        mats.append(D)
    return mats


def _closure(gens, ctx):
    """The subgroup generated by `gens` (the orbit of the identity under right
    multiplication)."""
    S = [ctx.e]
    seen = {ctx.e}
    i = 0
    while i < len(S):
        x = S[i]
        i += 1
        for h in gens:
            y = ctx.mt[x][h]
            if y not in seen:
                seen.add(y)
                S.append(y)
    return frozenset(S)


def subgroups_by_index(ctx, want_index):
    """The subgroups of index want_index, sorted by element list."""
    if ctx.n % want_index:
        return []
    want = ctx.n // want_index
    seen = set()
    found = set()
    frontier = []
    for g in range(ctx.n):
        H = _closure((g,), ctx)
        if want % len(H) or H in seen:
            continue
        seen.add(H)
        if len(H) == want:
            found.add(H)
        else:
            frontier.append(H)
    while frontier:
        H = frontier.pop()
        gens = tuple(sorted(H))
        for g in range(ctx.n):
            if g in H:
                continue
            K = _closure(gens + (g,), ctx)
            if want % len(K) or K in seen:
                continue
            seen.add(K)
            if len(K) == want:
                found.add(K)
            else:
                frontier.append(K)
    return sorted(found, key=lambda s: sorted(s))


def right_cosets(ctx, H):
    """The right cosets Hx, as sorted element lists, sorted by their first element."""
    seen = set()
    out = []
    for x in range(ctx.n):
        if x in seen:
            continue
        C = frozenset(ctx.mt[h][x] for h in H)
        seen |= set(C)
        out.append(sorted(C))
    out.sort(key=lambda c: c[0])
    return out


def coset_action(ctx, cosets):
    """sigma_g(i) = the coset of (representative of coset i) g."""
    where = {}
    for i, C in enumerate(cosets):
        for x in C:
            where[x] = i
    reps = [C[0] for C in cosets]
    return [[where[ctx.mt[reps[i]][g]] for i in range(len(cosets))] for g in range(ctx.n)]


def perm_dft(ctx, sigma, n):
    """D_kl(g) = (1/n) sum_i zeta_n^(i k - sigma_g(i) l), k, l = 1..n-1."""
    inv_n = Cyc.rational(F(1, n))
    mats = []
    for g in range(ctx.n):
        s = sigma[g]
        mats.append([[inv_n * csum([Cyc.zeta(n, (i * k - s[i] * l) % n) for i in range(n)])
                      for l in range(1, n)] for k in range(1, n)])
    return mats


def twist(ctx, mats, i):
    return [scale(mats[g], ctx.chi_el(i, g)) for g in range(ctx.n)]


def galois_twist(mats, M, j):
    return [[[lift(x, M).galois(j) for x in row] for row in D] for D in mats]


def build(ctx):
    """({irrep index: [D(g)]}, {irrep index: construction record})."""
    out = {}
    rec = {}
    lin = [i for i in range(len(ctx.irreps)) if ctx.irreps[i]["dim"] == 1]
    for i in lin:
        out[i] = build_linear(ctx, i)
        rec[i] = {"method": "linear", "note": "D(g) = [chi(g)]"}
    todo = [i for i in range(len(ctx.irreps)) if i not in out]

    blocks = axial_blocks(ctx)
    if blocks is not None:
        for i in list(todo):
            hit = None
            for k in range(1, 2 * ctx.n + 1):
                for a in (0, 1):
                    mats = axial_2d(blocks, k, a)
                    if ctx.match(mats) == i:
                        hit = (k, a, mats)
                        break
                if hit:
                    break
            k, a, mats = hit
            out[i] = mats
            rec[i] = {"method": "axial-monomial", "harmonic_k": k, "z_parity_exponent": a,
                      "basis": "{(x-iy)^k z^a, (x+iy)^k z^a}",
                      "note": "D = s^a * diag(conj w^k, w^k) when A(g) is a rotation and "
                              "s^a * [[0, w^k],[conj w^k, 0]] when A(g) is a reflection, "
                              "w = P11 + i P12, s = P33"}
            todo.remove(i)
        return out, rec

    nat = [ctx.P[g] for g in range(ctx.n)]
    i = ctx.match(nat)
    if i in todo:
        out[i] = nat
        rec[i] = {"method": "defining",
                  "basis": "the Cartesian frame of CONVENTIONS.md section 3",
                  "note": "D(g) = P(g) = elements.items[g].matrix, in the row-vector "
                          "convention of CONVENTIONS.md section 4"}
        todo.remove(i)

    M_el = 1
    for g in range(ctx.n):
        for row in ctx.P[g]:
            for x in row:
                M_el = M_el * x.M // gcd(M_el, x.M)

    progress = True
    while todo and progress:
        progress = False
        for i in list(todo):
            for j in sorted(out):
                if ctx.irreps[j]["dim"] != ctx.irreps[i]["dim"]:
                    continue
                for lam in lin:
                    mats = twist(ctx, out[j], lam)
                    if ctx.match(mats) == i:
                        out[i] = mats
                        rec[i] = {"method": "twist", "from": ctx.irreps[j]["id"],
                                  "by": ctx.irreps[lam]["id"],
                                  "note": "D = D^from (x) lambda, lambda 1-dimensional"}
                        todo.remove(i)
                        progress = True
                        break
                if i in out:
                    break
        for i in list(todo):
            for j in sorted(out):
                if ctx.irreps[j]["dim"] != ctx.irreps[i]["dim"]:
                    continue
                for t in range(2, M_el):
                    if gcd(t, M_el) != 1:
                        continue
                    mats = galois_twist(out[j], M_el, t)
                    if ctx.match(mats) == i:
                        out[i] = mats
                        rec[i] = {"method": "galois", "from": ctx.irreps[j]["id"],
                                  "sigma": t, "conductor": M_el,
                                  "note": "entrywise sigma_t: zeta_%d -> zeta_%d^%d"
                                          % (M_el, M_el, t)}
                        todo.remove(i)
                        progress = True
                        break
                if i in out:
                    break
        for i in list(todo):
            d = ctx.irreps[i]["dim"]
            if d + 1 > MAX_PERM_INDEX:
                continue
            for H in subgroups_by_index(ctx, d + 1):
                cos = right_cosets(ctx, H)
                sig = coset_action(ctx, cos)
                if all(Cyc.rational(F(sum(1 for a in range(d + 1) if sig[g][a] == a)))
                       == ctx.chi_el(i, g) + Cyc.one() for g in range(ctx.n)):
                    out[i] = perm_dft(ctx, sig, d + 1)
                    rec[i] = {"method": "perm-dft", "degree": d + 1,
                              "subgroup_order": len(H),
                              "subgroup_elements": sorted(H),
                              "cosets": [c[0] for c in cos],
                              "basis": "f_k = sum_j zeta_%d^{-jk} e_j,  k = 1..%d, on the "
                                       "sum-zero subspace of the coset permutation module, "
                                       "where g e_j' = e_j, j' the coset that contains xi_j g"
                                       % (d + 1, d),
                              "note": "D_kl(g) = (1/n) sum_i zeta_n^{i k - sigma_g(i) l}"}
                    todo.remove(i)
                    progress = True
                    break
    return out, rec


def attach(doc):
    """Set character_table.irreps[].matrices of the record."""
    ctx = Ctx(doc)
    mats, rec = build(ctx)
    for i, ir in enumerate(doc["character_table"]["irreps"]):
        ir["matrices"] = {
            "dim": ir["dim"],
            "construction": rec[i],
            "unitary": True,
            "by_element": [[[x.to_json() for x in row] for row in D] for D in mats[i]],
        }
