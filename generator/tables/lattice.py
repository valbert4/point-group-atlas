"""Subgroups of a finite point group: enumeration, conjugacy classes, normalizers and the O(3)
class of a subgroup.

A group is read from its record: its elements are the indices of elements.items[] and the product
is elements.multiplication_table (P(g) P(h) = P(gh)).  A subgroup is a set of indices, and
H^g = {g^-1 h g : h in H}.
"""
from fractions import Fraction as F


class Grp:
    """A finite group as its record holds it: multiplication table, inverses, determinants,
    turns, symbols, poles and class ids of its elements."""

    __slots__ = ("name", "order", "mt", "inv", "det", "turn", "sym", "pole", "cls",
                 "identity_index")

    def __init__(self, name, doc):
        self.name = name
        self.order = doc["group"]["order"]
        el = doc["elements"]
        self.identity_index = el["identity_index"]
        self.mt = el["multiplication_table"]
        items = el["items"]
        self.inv = [e["inverse"] for e in items]
        self.det = [e["det"] for e in items]
        # the rotation angle (det = +1) or rotoreflection angle (det = -1), in turns
        self.turn = [F(e["angle"][0], e["angle"][1]) % 1 for e in items]
        self.sym = [e["symbol"] for e in items]
        self.pole = [e["pole"] for e in items]
        self.cls = [e["class_id"] for e in items]

    def conj(self, g, x):
        """g^-1 x g."""
        return self.mt[self.mt[self.inv[g]][x]][g]


# ---------------------------------------------------------------- subgroups
def closure(G, gens):
    """The subgroup generated by the elements `gens`, as a frozenset."""
    e = G.identity_index
    S = {e}
    frontier = [e]
    for g in gens:
        if g not in S:
            S.add(g)
            frontier.append(g)
    while frontier:
        a = frontier.pop()
        for b in list(S):
            for p in (G.mt[a][b], G.mt[b][a]):
                if p not in S:
                    S.add(p)
                    frontier.append(p)
    return frozenset(S)


def all_subgroups(G):
    """Every subgroup of G, as frozensets of element indices, sorted by (order, element list).

    Every subgroup K that properly contains a subgroup H is generated by H and one element of
    K \\ H, so adjoining single elements to the subgroups found so far, starting from the trivial
    group, reaches all of them.  <H, g> = <H, h g h'> for h, h' in H, so one g per double coset
    HgH is adjoined."""
    e = G.identity_index
    triv = frozenset([e])
    found = {triv}
    level = [triv]
    while level:
        nxt = []
        for H in level:
            Hl = list(H)
            used = set(H)
            for g in range(G.order):
                if g in used:
                    continue
                for a in Hl:
                    ag = G.mt[a][g]
                    for b in Hl:
                        used.add(G.mt[ag][b])
                K = closure(G, Hl + [g])
                if K not in found:
                    found.add(K)
                    nxt.append(K)
        level = nxt
    return sorted(found, key=lambda s: (len(s), sorted(s)))


def conjugate_subgroup(G, H, g):
    """H^g."""
    return frozenset(G.conj(g, x) for x in H)


def subgroup_classes(G, subs):
    """The G-conjugacy classes of the subgroups `subs` (sorted as all_subgroups returns them),
    sorted by (order, element list of the representative).  Each class: "rep" (the member with
    the smallest element list), "members" (sorted by element list) and "conjugators" (for each
    member, the smallest g with member = rep^g)."""
    seen = set()
    classes = []
    for H in subs:
        if H in seen:
            continue
        orbit = {}
        for g in range(G.order):
            K = conjugate_subgroup(G, H, g)
            orbit.setdefault(K, g)
        seen |= set(orbit)
        rep = min(orbit, key=lambda s: sorted(s))
        classes.append({
            "rep": rep,
            "members": sorted(orbit, key=lambda s: sorted(s)),
            "conjugators": {k: v for k, v in orbit.items()},
        })
    classes.sort(key=lambda c: (len(c["rep"]), sorted(c["rep"])))
    return classes


def normalizer(G, H):
    """N_G(H), as a list of element indices."""
    return [g for g in range(G.order) if conjugate_subgroup(G, H, g) == H]


def centralizer(G, H):
    """C_G(H) = {g : g h = h g for every h in H}, as a list of element indices."""
    return [g for g in range(G.order) if all(G.mt[g][h] == G.mt[h][g] for h in H)]


def center(G):
    """Z(G) = {z : z g = g z for every g in G}, as a frozenset."""
    return frozenset(centralizer(G, range(G.order)))


def commutator_subgroup(G):
    """[G, G], the subgroup generated by the commutators g h g^-1 h^-1, as a frozenset."""
    return closure(G, {G.mt[G.mt[g][h]][G.mt[G.inv[g]][G.inv[h]]]
                       for g in range(G.order) for h in range(G.order)})


# ---------------------------------------------------------------- O(3) classes
def fingerprint(G, H):
    """The multiset of (det, turn) over the elements of H.  Conjugation in O(3) preserves the
    determinant and the rotation or rotoreflection angle, so the multiset is the same for
    O(3)-conjugate subgroups; over the finite groups of the catalogue it separates the O(3)
    classes."""
    return tuple(sorted((G.det[x], G.turn[x].numerator, G.turn[x].denominator)
                        for x in H))


