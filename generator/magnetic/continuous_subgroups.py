"""The closed subgroups of the continuous magnetic groups up to conjugation in them
(magnetic/CONVENTIONS.md section 37.5), from the closed subgroups of the point group G in its record
(`subduction_subgroups` of the axial groups, `subgroup_classes` of SO(3) and O(3)).

Over each closed subgroup K of G lies K itself (magnetic type I), when it lies in H, or K(K & H)
(type III) in a group G(H); and K (type I), K1' (type II) and K(K') (type III) in a group G1', K'
over the orbits of the normalizer of K in G on the closed subgroups of index 2 of K.  Time reversal
commutes with every element, so the normalizer of K1' in G1' is N_G(K)1', that of K(K') the part of
it that fixes K', and the centralizers are C_G(K)1'.

An axial group is computed as its set of elements in the frame of D_inf_h, each (whether it reflects
the plane, its angle in turns, its sign on z).  A subgroup of SO(3) or O(3) is named by the record
of its O(3)-conjugacy class: two subgroups of index 2 of K are carried to each other by the
normalizer of K exactly when they have one class (names.halves), and the normalizer of K(K') in O(3)
x C_2^T is in its record (section 30.4).
"""
import re
from fractions import Fraction as F

from .. import names, serialize
from . import pointer
from .continuous import (CONTINUOUS, OF_COMPONENTS, OUTSIDE, Magnetic, _null,
                         normalizer_centralizer, rot)


# --------------------------------------------------------------- the closed subgroups: axial groups
def planar(component, turn):
    """An element of D_inf_h as (reflects the plane, angle in turns, sign on z): the rotation of the
    plane by the angle, or the reflection x -> angle - x of its azimuths."""
    t = F(*turn) if not isinstance(turn, F) else turn
    return {"Cphi": (0, t % 1, 1), "iCphi": (0, (t + F(1, 2)) % 1, -1),
            "sv": (1, (2 * t) % 1, 1), "c2p": (1, (2 * t) % 1, -1)}[component]


def component_of(x):
    return {(0, 1): "Cphi", (0, -1): "iCphi", (1, 1): "sv", (1, -1): "c2p"}[(x[0], x[2])]


def compose(x, y):
    """x after y."""
    if x[0] == 0:
        return (y[0], (x[1] + y[1]) % 1, x[2] * y[2])
    return (1 - y[0], (x[1] - y[1]) % 1, x[2] * y[2])


def inverse(x):
    return x if x[0] else (0, -x[1] % 1, x[2])


def conjugated(g, S):
    gi = inverse(g)
    return frozenset(compose(compose(g, s), gi) for s in S)


SIGMA_H = (0, F(0), -1)


def family_of(S):
    """(family, N) of a finite axial group in the frame of D_inf_h."""
    n = sum(1 for x in S if (x[0], x[2]) == (0, 1))
    comps = {component_of(x) for x in S}
    if "iCphi" not in comps:
        f = "Cnv" if "sv" in comps else "Dn" if "c2p" in comps else "Cn"
    elif SIGMA_H in S:
        f = "Dnh" if "sv" in comps else "Cnh"
    else:
        f = "Dnd" if "sv" in comps else "S2n"
    return f, n


def member(family, N):
    """The member N of an axial family in the frame of its record: a binary axis at azimuth 0 (a
    vertical mirror, in C_Nv)."""
    S = {(0, F(k, N), 1) for k in range(N)}
    if family in ("S2n", "Dnd"):
        S |= {(0, F(2 * k + 1, 2 * N), -1) for k in range(N)}
    if family in ("Cnh", "Dnh"):
        S |= {(0, F(k, N), -1) for k in range(N)}
    if family in ("Cnv", "Dnh"):
        S |= {(1, F(k, N), 1) for k in range(N)}
    if family in ("Dn", "Dnh", "Dnd"):
        S |= {(1, F(k, N), -1) for k in range(N)}
    if family == "Dnd":
        S |= {(1, F(2 * k + 1, 2 * N), 1) for k in range(N)}
    return frozenset(S)


def generated(S):
    out = set(S) | {(0, F(0), 1)}
    while True:
        new = {compose(x, y) for x in out for y in out} - out
        if not new:
            return frozenset(out)
        out |= new


def index_two(K):
    """The subgroups of index 2 of a finite group K of elements: the unions of cosets of the
    subgroup generated by the squares that a character of order 2 of the quotient sends to +1."""
    base = generated({compose(x, x) for x in K})
    cosets, seen = [], set()
    for x in sorted(K):
        if x not in seen:
            c = frozenset(compose(x, b) for b in base)
            cosets.append(c)
            seen |= c
    rank = len(cosets).bit_length() - 1
    if 1 << rank != len(cosets):
        raise AssertionError("the quotient by the squares")
    out = []
    for mask in range(1, 1 << len(cosets)):
        pass_ = [c for k, c in enumerate(cosets) if not mask >> k & 1]
        if 2 * len(pass_) != len(cosets) or base not in pass_:
            continue
        S = frozenset().union(*pass_)
        if all(compose(x, y) in S for x in S for y in S):
            out.append(S)
    return out


# The families of the subgroups of index 2 of a member of a family, in the order of names.halves:
# those with the same rotations about the axis, then those about half of them.
HALVES = {"Cn": (), "S2n": ("Cn",), "Cnh": ("Cn",), "Cnv": ("Cn",), "Dn": ("Cn",),
          "Dnh": ("Dn", "Cnh", "Cnv"), "Dnd": ("Dn", "S2n", "Cnv")}
HALF_AXIS = {"Cn": ("Cn",), "Cnh": ("Cnh", "S2n"), "Cnv": ("Cnv",), "Dn": ("Dn",),
             "Dnh": ("Dnh", "Dnd")}


def half_rank(K, S):
    f, N = family_of(K)
    g, k = family_of(S)
    return (0, HALVES[f].index(g)) if k == N else (1, HALF_AXIS[f].index(g))


def about_axis(K):
    """Whether K has no element that reflects the plane: then D_inf_h normalizes it and each of its
    subgroups."""
    return not any(x[0] for x in K)


class AxialSubgroups:
    """The closed subgroups of an axial continuous group G (`subduction_subgroups`)."""

    def __init__(self, G):
        self.G = G
        self.comps = set(G.components)
        self.block = G.rec["subduction_subgroups"]
        self.entry = {}
        for e in self.block["finite"]:
            s = e["subgroup"]
            K = frozenset(planar(x["component"], x["turn"]) for x in e["elements"])
            if K != member(s["family"], s["N"]) or family_of(K) != (s["family"], s["N"]):
                raise AssertionError("%s: the member %s" % (G.stem, s))
            self.entry[(s["family"], s["N"])] = (e, K)

    def normalizer(self, K):
        """N_G(K) as a set of elements, or None where it is the whole of G."""
        if about_axis(K):
            return None
        N = family_of(K)[1]
        out = set()
        for k in range(4 * N):
            for r in (0, 1):
                for s in (1, -1):
                    g = (r, F(k, 4 * N), s)
                    if component_of(g) in self.comps and conjugated(g, K) == K:
                        out.add(g)
        return frozenset(out)


def stem_name(f, N):
    return names.name_of(f, N)


def sch(stem):
    return names.schoenflies_of(stem)


def finite_stem(S):
    return stem_name(*family_of(S))


def magnetic_symbol(stem, unitary):
    """The symbol of a subgroup over `stem` with the unitary half `unitary` (a stem; the stem itself
    in type I; None in type II)."""
    if unitary is None:
        return sch(stem) + "1'"
    return sch(stem) if unitary == stem else "%s(%s)" % (sch(stem), sch(unitary))


def class_symbol(stem, unitary):
    """The symbol of a normalizer or of a centralizer, with C_i for S_2 and C_s for C_1v, as in the
    records of the point groups (section 15.1)."""
    symbol = names.display_schoenflies(stem)
    if unitary is None:
        return symbol + "1'"
    return symbol if unitary == stem else "%s(%s)" % (symbol, names.display_schoenflies(unitary))


def magnetic_record(stem, unitary):
    """The pointer to the record of that subgroup, or the null outside the catalogue."""
    if unitary == stem:
        return rot(stem) if stem in names.NAMES else _null(OUTSIDE)
    half = "1p" if unitary is None else names.CLASS_RECORD.get(unitary, unitary)
    name = "%s-%s" % (stem, half)
    return pointer("magnetic", name) if name in names.MAGNETIC_NAMES else _null(OUTSIDE)


def kind_of(stem, unitary):
    return "II" if unitary is None else "I" if unitary == stem else "III"


def entry(stem, unitary, normalizer, centralizer, half=None):
    """An entry of subgroup_classes (section 37.5): the subgroup over the group of the record `stem`
    with the unitary half `unitary`, `half` the family and N of that half where its group is of a
    family and it is not the whole."""
    out = {"magnetic_type": kind_of(stem, unitary), "symbol": magnetic_symbol(stem, unitary),
           "record": magnetic_record(stem, unitary), "normalizer": normalizer,
           "centralizer": centralizer}
    if half:
        out["unitary"] = {"family": half[0], "N": half[1]}
    return out


def grey_entry(stem, unitary, order, normal, normalizer, centralizer, family=None, half=None):
    """An entry of a group of magnetic type II, with what the entry of its K does not give: its
    order, the number of its conjugates and whether it is normal, and the family and N of K."""
    out = entry(stem, unitary, normalizer, centralizer, half)
    out.update({"order": order if order is not None else _null(CONTINUOUS),
                "class_size": 1 if normal else _null(CONTINUOUS), "normal": normal})
    if family:
        out["group"] = {"family": family[0], "N": family[1]}
    return out


CONTINUOUS_COMPONENTS = {"Cinf": {"Cphi"}, "Cinfh": {"Cphi", "iCphi"}, "Cinfv": {"Cphi", "sv"},
                         "Dinf": {"Cphi", "c2p"}, "Dinfh": {"Cphi", "iCphi", "sv", "c2p"}}


def meet(stem, comps):
    """The subgroup of the elements of the components `comps` of an axial group in the frame of its
    record, a stem."""
    if stem in CONTINUOUS_COMPONENTS:
        return OF_COMPONENTS[frozenset(CONTINUOUS_COMPONENTS[stem] & comps)]
    f, N = names.family_of(stem)
    return finite_stem(frozenset(x for x in member(f, N) if component_of(x) in comps))


def stem_of_symbol(s):
    """The stem of a Schoenflies symbol: C_24v -> C24v, SO(3) -> SO3, C_i -> S2."""
    return {"C_i": "S2", "C_s": "C1v"}.get(s) or re.sub(r"[_()]", "", s)


def axial_black_white(M):
    """subgroup_classes of an axial group of magnetic type III: one entry for each entry of G, in
    its order; the normalizers and the centralizers are those of G, read in M."""
    A = AxialSubgroups(M.G)
    inside = set(M.inside)

    def over(stem):
        return class_symbol(stem, meet(stem, inside))
    out = {"continuous": [], "finite": []}
    for e in A.block["continuous"]:
        stem = e["subgroup"]["o3_class"]
        out["continuous"].append(entry(
            stem, meet(stem, inside), over(stem_of_symbol(e["normalizer"]["schoenflies"])),
            over(stem_of_symbol(e["centralizer"]["schoenflies"]))))
    for e in A.block["finite"]:
        s = e["subgroup"]
        stem = stem_name(s["family"], s["N"])
        unitary = meet(stem, inside)
        out["finite"].append(entry(
            stem, unitary, over(stem_of_symbol(e["normalizer"]["schoenflies"])),
            over(stem_of_symbol(e["centralizer"]["schoenflies"])),
            names.family_of(unitary) if unitary != stem else None))
    return out


def axial_grey(M):
    """subgroup_classes of an axial group of magnetic type II: over each entry K of G the groups K,
    K1' and K(K'), K' over the orbits of the normalizer of K in G on the subgroups of index 2 of
    K."""
    G = M.G
    A = AxialSubgroups(G)
    whole = sch(G.stem) + "1'"
    out = {"continuous": [], "finite": []}
    continuous = [(e["subgroup"]["o3_class"], e["centralizer"]["schoenflies"])
                  for e in A.block["continuous"]] + [(G.stem, None)]
    for stem, cent in continuous:
        if cent is None:
            cent = meet(stem_of_symbol(G.group["centralizer"]["schoenflies"]), A.comps)
            cent = sch(cent)
        for unitary in (stem, None) + names.halves(stem):
            if stem == G.stem and unitary is None:
                continue
            out["continuous"].append(grey_entry(stem, unitary, None, True, whole, cent + "1'"))
    for e in A.block["finite"]:
        s = e["subgroup"]
        K = A.entry[(s["family"], s["N"])][1]
        stem = stem_name(s["family"], s["N"])
        fam = (s["family"], s["N"])
        NK = A.normalizer(K)
        got = G.group["schoenflies"] if NK is None else sch(finite_stem(NK))
        if got != e["normalizer"]["schoenflies"] or (
                NK is not None and len(NK) != e["normalizer"]["order"]):
            raise AssertionError("%s: the normalizer of %s: %s" % (G.stem, stem, got))
        cent = e["centralizer"]["schoenflies"] + "1'"
        norm = got + "1'"
        normal = NK is None
        if normal != e["normal"] or (e["class_size"] == 1) != normal:
            raise AssertionError("%s: the class of %s" % (G.stem, stem))
        out["finite"].append(grey_entry(stem, stem, s["order"], normal, norm, cent, fam))
        out["finite"].append(grey_entry(stem, None, 2 * s["order"], normal, norm, cent, fam))
        left = sorted(index_two(K), key=lambda S: (half_rank(K, S), member(*family_of(S)) != S))
        while left:
            S = left[0]
            if NK is None:
                orbit, stab = {S}, None
            else:
                orbit = {conjugated(g, S) for g in NK}
                stab = frozenset(g for g in NK if conjugated(g, S) == S)
            left = [x for x in left if x not in orbit]
            symbol = G.group["schoenflies"] if stab is None else sch(finite_stem(stab))
            out["finite"].append(grey_entry(stem, finite_stem(S), s["order"], stab is None,
                                            symbol + "1'", cent, fam, family_of(S)))
    return out


# ------------------------------------------------------------- the closed subgroups: SO(3) and O(3)
def rotations(stem):
    """The stem of the rotation subgroup of a point group, by its name."""
    if stem in names.EXCEPTIONAL:
        return stem[0]
    if stem in names.CONTINUOUS:
        return {"Cinf": "Cinf", "Cinfh": "Cinf", "Cinfv": "Cinf", "Dinf": "Dinf", "Dinfh": "Dinf",
                "SO3": "SO3", "O3": "SO3"}[stem]
    f, N = names.family_of(stem)
    return stem_name("Dn" if f[0] == "D" else "Cn", N)


def canonical(stem):
    return names.CLASS_RECORD.get(stem, stem)


def spherical_entries(G):
    """[(stem, family, N, order or None, normal, normalizer, centralizer)] of the closed subgroups
    of G."""
    out = []
    block = G.rec["subgroup_classes"]
    for e in block["continuous"] + block["finite"]:
        s = e["subgroup"]
        order = s.get("order")
        out.append((s["o3_class"], s.get("family"), s.get("N"),
                    order if isinstance(order, int) else None, e["normal"],
                    stem_of_symbol(e["normalizer"]["schoenflies"]),
                    stem_of_symbol(e["centralizer"]["schoenflies"])))
    return out


def spherical_black_white(M):
    """subgroup_classes of O(3)(SO(3)): K, or K(K & SO(3)), over each class of O(3)."""
    def over(stem):
        return class_symbol(stem, rotations(stem))
    out = {"continuous": [], "finite": []}
    for stem, f, _, order, _, norm, cent in spherical_entries(M.G):
        unitary = stem if rotations(stem) == stem else canonical(rotations(stem))
        out["continuous" if order is None else "finite"].append(entry(
            stem, unitary, over(norm), over(cent),
            names.family_of(unitary) if f and unitary != stem else None))
    return out


def point_part(M, symbol):
    """The point group of the symbol of a normalizer in O(3) x C_2^T, read in G: its rotations in
    SO(3)."""
    stem = stem_of_symbol(symbol[:-2])
    return stem if M.G.stem == "O3" else rotations(stem)


def spherical_grey(M):
    """subgroup_classes of SO(3)1' and O(3)1': over each class K of G the groups K, K1' and K(K'),
    one for each class K' of names.halves, which two subgroups of index 2 of K share exactly when
    the normalizer of K carries one to the other; the normalizer of K(K') is that of its record,
    read in G (section 30.4)."""
    G = M.G
    out = {"continuous": [], "finite": []}
    rows = spherical_entries(G)
    rows.insert(sum(1 for r in rows if r[3] is None),
                (G.stem, None, None, None, True, G.stem, center(G)))
    for stem, f, N, order, normal, norm, cent in rows:
        fam = (f, N) if f else None
        part = out["continuous" if order is None else "finite"]
        c = class_symbol(cent, None)
        for unitary in (stem, None) + names.halves(stem):
            if stem == G.stem and unitary is None:
                continue
            if G.stem == "SO3" and unitary not in (stem, None) and rotations(unitary) != unitary:
                raise AssertionError("SO(3): a half %s of %s" % (unitary, stem))
            n = norm
            if unitary not in (stem, None) and stem != G.stem:
                if stem in names.CONTINUOUS:
                    symbol = normalizer_centralizer(Magnetic(stem, unitary))[0]["symbol"]
                else:
                    path = "%s/%s-%s.json" % (names.RECORDS_DIR, stem, unitary)
                    symbol = serialize.read_json(names.catalogue_path("magnetic", path))["group"][
                        "normalizer"]["symbol"]
                n = point_part(M, symbol)
            if (n == G.stem) != normal and unitary in (stem, None):
                raise AssertionError("%s: the class of %s" % (G.stem, stem))
            part.append(grey_entry(
                stem, unitary, None if order is None else order * (2 if unitary is None else 1),
                n == G.stem, class_symbol(n, None), c, fam,
                names.family_of(unitary) if f and unitary not in (stem, None) else None))
    return out


def center(G):
    """The center of G, a stem."""
    return canonical(stem_of_symbol(G.group["center"]["schoenflies"]))


# ---------------------------------------------------------------- the continuous subgroups, ordered
def cosets(stem, unitary):
    """The components of a continuous magnetic group with their signs: {(component, theta)}; those
    of SO(3) and O(3) with the component of every rotation, "SO3", and its product with the
    inversion."""
    if stem in ("SO3", "O3"):
        comps = {"Cphi", "c2p"} | ({"iCphi", "sv"} if stem == "O3" else set())
        inside = comps if unitary == stem else {"Cphi", "c2p"}
        extra = {"all"}
    else:
        comps = CONTINUOUS_COMPONENTS[stem]
        inside = comps if unitary in (stem, None) else CONTINUOUS_COMPONENTS[unitary]
        extra = set()
    out = {(c, 1 if c in inside else -1) for c in comps}
    if unitary is None:
        out = {(c, t) for c in comps for t in (1, -1)}
    return out | extra


def name_of_group(stem, unitary):
    return stem if unitary == stem else stem + "-" + ("1p" if unitary is None else unitary)


def edges(groups):
    """The covering edges among continuous magnetic groups [(stem, unitary)]: {lower, upper} by
    their records' names."""
    sets = {name_of_group(*g): cosets(*g) for g in groups}
    order = list(sets)
    below = {a: {b for b in order if b != a and sets[b] < sets[a]} for a in order}
    return [{"lower": b, "upper": a} for a in order for b in order
            if b in below[a] and not any(b in below[c] for c in below[a])]


def subgroup_classes(M):
    """The field subgroup_classes (section 37.5)."""
    G = M.G
    if G.spherical:
        out = spherical_grey(M) if M.grey else spherical_black_white(M)
        key = "subgroup_classes"
    else:
        out = axial_grey(M) if M.grey else axial_black_white(M)
        key = "subduction_subgroups"
    groups = []
    for e in out["continuous"]:
        p = e["record"].split("#")[0].split("/")[1]
        stem, _, half = p.partition("-")
        groups.append((stem, stem if not half else None if half == "1p" else half))
    groups.append((G.stem, None if M.grey else M.H.stem))
    out["edges"] = edges(groups)
    out["classes"] = rot(G.stem, "/" + key)
    return out
