# ---------------------------------------------------------------- exact scalars
def as_rational(x):
    """The rational number x, or None when x is irrational."""
    return x.c[0] if not any(x.c[1:]) else None


def real_sign(x):
    """The sign of a real element of Q(zeta_M): exact for a rational, otherwise from its value
    in floating point, which is used only when it lies outside a margin that bounds the
    rounding error (1e-9 times one plus the sum of the absolute coordinates)."""
    r = as_rational(x)
    if r is not None:
        return (r > 0) - (r < 0)
    z = x.to_float()
    m = 1e-9 * (1.0 + float(sum(abs(c) for c in x.c)))
    if abs(z.imag) > m or abs(z.real) < m:
        raise ArithmeticError("the sign of %r is not determined" % (x,))
    return 1 if z.real > 0 else -1


def two_cos(M, q):
    """2 cos(2 pi q / M) = zeta_M^q + zeta_M^-q."""
    return Cyc.zeta(M, q) + Cyc.zeta(M, -q)


class QS:
    """a + b sqrt 5, a and b rational."""

    __slots__ = ("a", "b")

    def __init__(self, a=0, b=0):
        self.a = F(a)
        self.b = F(b)

    def __add__(self, o):
        o = o if isinstance(o, QS) else QS(o)
        return QS(self.a + o.a, self.b + o.b)

    __radd__ = __add__

    def __neg__(self):
        return QS(-self.a, -self.b)

    def __sub__(self, o):
        return self + (-(o if isinstance(o, QS) else QS(o)))

    def __mul__(self, o):
        o = o if isinstance(o, QS) else QS(o)
        return QS(self.a * o.a + 5 * self.b * o.b, self.a * o.b + self.b * o.a)

    __rmul__ = __mul__

    def sign(self):
        """The sign of a + b sqrt 5, exactly."""
        a, b = self.a, self.b
        if b == 0:
            return (a > 0) - (a < 0)
        if a == 0:
            return (b > 0) - (b < 0)
        if a > 0 and b > 0:
            return 1
        if a < 0 and b < 0:
            return -1
        d = a * a - 5 * b * b
        if d == 0:
            return 0
        big_a = d > 0
        return (1 if big_a else -1) if a > 0 else (-1 if big_a else 1)

    def is_zero(self):
        return self.a == 0 and self.b == 0


def qs_to_cyc(x):
    """a + b sqrt 5 as an element of Q(zeta_5): sqrt 5 = zeta_5 - zeta_5^2 - zeta_5^3 + zeta_5^4."""
    v = Cyc.rational(F(x.a))
    if x.b:
        r5 = Cyc.zeta(5, 1) - Cyc.zeta(5, 2) - Cyc.zeta(5, 3) + Cyc.zeta(5, 4)
        v = v + Cyc.rational(F(x.b)) * r5
    return v


# ---------------------------------------------------------------- axial operations
class AxOp:
    """The operation (r, u, s) of the module docstring."""

    __slots__ = ("r", "u", "s")

    def __init__(self, r, u, s):
        self.r = int(r)
        self.u = F(u) % 1
        self.s = int(s)

    def key(self):
        return (self.r, self.u, self.s)

    def __eq__(self, o):
        return isinstance(o, AxOp) and self.key() == o.key()

    def __mul__(self, o):
        if self.r == 0 and o.r == 0:
            return AxOp(0, self.u + o.u, self.s * o.s)
        if self.r == 0 and o.r == 1:
            return AxOp(1, o.u + self.u, self.s * o.s)
        if self.r == 1 and o.r == 0:
            return AxOp(1, self.u - o.u, self.s * o.s)
        return AxOp(0, self.u - o.u, self.s * o.s)

    def inv(self):
        if self.r == 0:
            return AxOp(0, -self.u, self.s)
        return AxOp(1, self.u, self.s)


AX_E = AxOp(0, 0, 1)
AX_SH = AxOp(0, 0, -1)                  # sigma_h
AX_I = AxOp(0, F(1, 2), -1)             # the inversion
AX_C2X = AxOp(1, 0, -1)                 # C_2' = C_2x
AX_SV = AxOp(1, 0, 1)                   # sigma_v, the xz plane


def _axial_generators(family, N):
    """The generators of CONVENTIONS.md section 3; S_2N is generated by sigma_h R_z(pi/N)."""
    rot = AxOp(0, F(1, N), 1)
    s2n = AxOp(0, F(1, 2 * N), -1)
    return {"Cn": [rot],
            "Cnh": [rot, AX_SH],
            "Cnv": [rot, AX_SV],
            "Dn": [rot, AX_C2X],
            "S2n": [s2n],
            "Dnh": [rot, AX_C2X, AX_SH],
            "Dnd": [s2n, AX_C2X]}[family]


# ---------------------------------------------------------------- 3x3 matrices over Q(sqrt 5)
def _M(rows):
    return tuple(tuple(x if isinstance(x, QS) else QS(x) for x in row) for row in rows)


def mat_mul(A, B):
    return tuple(tuple(A[i][0] * B[0][j] + A[i][1] * B[1][j] + A[i][2] * B[2][j]
                       for j in range(3)) for i in range(3))


def mat_neg(A):
    return tuple(tuple(-x for x in row) for row in A)


def mat_trace(A):
    return A[0][0] + A[1][1] + A[2][2]


def mat_det(A):
    return (A[0][0] * (A[1][1] * A[2][2] - A[1][2] * A[2][1])
            - A[0][1] * (A[1][0] * A[2][2] - A[1][2] * A[2][0])
            + A[0][2] * (A[1][0] * A[2][1] - A[1][1] * A[2][0]))


def mat_inv(A):
    """The inverse of an orthogonal matrix, its transpose."""
    return tuple(tuple(A[j][i] for j in range(3)) for i in range(3))


IDENTITY = _M([[1, 0, 0], [0, 1, 0], [0, 0, 1]])
_C4Z = _M([[0, -1, 0], [1, 0, 0], [0, 0, 1]])
_C3D = _M([[0, 0, 1], [1, 0, 0], [0, 1, 0]])
_C2Z = _M([[-1, 0, 0], [0, -1, 0], [0, 0, 1]])
_S4Z = mat_neg(_C4Z)
_h = F(1, 2)
_q = F(1, 4)
_C5 = _M([[QS(-_q, _q), QS(-_q, -_q), QS(_h, 0)],
          [QS(_q, _q), QS(_h, 0), QS(-_q, _q)],
          [QS(-_h, 0), QS(-_q, _q), QS(_q, _q)]])

EXCEPTIONAL_GENS = {
    "T": [_C2Z, _C3D],
    "Th": [_C2Z, _C3D, mat_neg(IDENTITY)],
    "Td": [_C2Z, _C3D, _S4Z],
    "O": [_C4Z, _C3D],
    "Oh": [_C4Z, _C3D, mat_neg(IDENTITY)],
    "I": [_C5, _C3D],
    "Ih": [_C5, _C3D, mat_neg(IDENTITY)],
}


def mat_key(A):
    return tuple((x.a, x.b) for row in A for x in row)


def _close(gens, mul, key, ident):
    """The group generated by `gens`, in the order the elements are reached from the
    identity."""
    G = {key(ident): ident}
    frontier = [ident]
    while frontier:
        nxt = []
        for A in frontier:
            for g in gens:
                B = mul(g, A)
                k = key(B)
                if k not in G:
                    G[k] = B
                    nxt.append(B)
        frontier = nxt
    return list(G.values())


# cos(2 pi t) of the rotation angles t <= 1/2 that occur in the exceptional groups
COS_TURN = {
    F(1, 2): QS(-1, 0),
    F(1, 3): QS(F(-1, 2), 0),
    F(1, 4): QS(0, 0),
    F(1, 5): QS(F(-1, 4), F(1, 4)),
    F(2, 5): QS(F(-1, 4), F(-1, 4)),
    F(1, 6): QS(F(1, 2), 0),
    F(1, 10): QS(F(1, 4), F(1, 4)),
    F(3, 10): QS(F(1, 4), F(-1, 4)),
}


def _abs_turn_from_trace(tr):
    """The rotation angle t in [0, 1/2] (in turns) of a rotation with trace
    tr = 1 + 2 cos 2 pi t."""
    if (tr - QS(3)).is_zero():
        return F(0)
    c2 = tr - QS(1)
    for f, c in COS_TURN.items():
        if (c2 - QS(2) * c).is_zero():
            return f
    raise ValueError("trace %r is not the trace of a rotation of the exceptional groups" % (tr,))


def _axis_of_rotation(A, half):
    """A vector along the axis of the rotation A (half: A is a rotation by 1/2 turn)."""
    if not half:
        return (A[2][1] - A[1][2], A[0][2] - A[2][0], A[1][0] - A[0][1])
    B = tuple(tuple(A[i][j] + (QS(1) if i == j else QS(0)) for j in range(3)) for i in range(3))
    for j in range(3):
        col = (B[0][j], B[1][j], B[2][j])
        if any(not x.is_zero() for x in col):
            return col


def _pole(v):
    """The pole of an axis: the direction v or -v in the positive hemisphere (z > 0, then x > 0,
    then y > 0), except that a body diagonal (|x| = |y| = |z|) is the one with x y z > 0."""
    sx, sy, sz = v[0].sign(), v[1].sign(), v[2].sign()
    if sx and sy and sz:
        ax, ay, az = v[0] * v[0], v[1] * v[1], v[2] * v[2]
        if (ax - ay).is_zero() and (ay - az).is_zero():
            return v if sx * sy * sz > 0 else tuple(-x for x in v)
    for c, s in ((v[2], sz), (v[0], sx), (v[1], sy)):
        if s:
            return v if s > 0 else tuple(-x for x in v)
    return v


def _signed_turn(A):
    """(pole, turn) of a rotation A: the rotation is by `turn` counterclockwise about its pole."""
    f = _abs_turn_from_trace(mat_trace(A))
    if f == 0:
        return None, F(0)
    ax = _axis_of_rotation(A, f == F(1, 2))
    pole = _pole(ax)
    if f == F(1, 2):
        return pole, F(1, 2)
    s = (A[2][1] - A[1][2], A[0][2] - A[2][0], A[1][0] - A[0][1])
    d = sum((s[i] * pole[i] for i in range(3)), QS(0)).sign()
    return pole, (f if d > 0 else (1 - f))


def _mat_geom(A):
    """(det, turn, pole) of an orthogonal matrix; for det = -1 the turn is the rotoreflection
    angle, -A being the rotation by turn + 1/2."""
    d = mat_det(A)
    if (d - QS(1)).is_zero():
        pole, t = _signed_turn(A)
        return 1, t, pole
    pole, t = _signed_turn(mat_neg(A))
    return -1, (t + F(1, 2)) % 1, pole


# ---------------------------------------------------------------- groups and classes
class ClassInfo:
    """A conjugacy class: size, det and turn of its first member, the axis kind ("z", "perp",
    "mirror" for axial groups, "general" for exceptional ones), the axis parameters of its
    members, `reps` the geometry of every member and `members` the operations."""

    __slots__ = ("index", "size", "det", "turn", "axis", "param", "reps", "members")

    def __init__(self, index, size, det, turn, axis, param, reps, members):
        self.index, self.size = index, size
        self.det, self.turn, self.axis, self.param = det, turn, axis, param
        self.reps, self.members = reps, members


class Ctx:
    """A group: its name, kind ("axial" or "exceptional"), elements, classes (in the order
    they are found) and whether it contains the inversion and sigma_h."""

    def __init__(self, name, kind, elements, classes, has_i, has_sh, order):
        self.name, self.kind, self.elements = name, kind, elements
        self.classes, self.order = classes, order
        self.has_i, self.has_sh = has_i, has_sh


def _conj_classes(elems, mul, inv, key, gens):
    """The conjugacy classes, as sorted lists of element indices, in the order of their first
    element."""
    idx = {key(g): i for i, g in enumerate(elems)}
    seen = set()
    out = []
    for i, g in enumerate(elems):
        if i in seen:
            continue
        orb = {i}
        frontier = [g]
        while frontier:
            nxt = []
            for x in frontier:
                for h in gens:
                    y = mul(mul(h, x), inv(h))
                    j = idx[key(y)]
                    if j not in orb:
                        orb.add(j)
                        nxt.append(y)
            frontier = nxt
        seen |= orb
        out.append(sorted(orb))
    return out


def _ax_geom(g):
    """(det, turn, axis kind, axis parameter) of an axial operation; the parameter of a binary
    axis or a vertical mirror is u, its azimuth in half turns."""
    if g.r == 0:
        return (g.s, g.u, "z", None)
    if g.s == -1:
        return (1, F(1, 2), "perp", g.u)
    return (-1, F(0), "mirror", g.u)


_CTX_CACHE = {}


def context(name):
    """The group of a finite group name."""
    if name in _CTX_CACHE:
        return _CTX_CACHE[name]
    if names.kind_of(name) == "exceptional":
        gens = EXCEPTIONAL_GENS[name]
        elems = _close(gens, mat_mul, mat_key, IDENTITY)
        cls = _conj_classes(elems, mat_mul, mat_inv, mat_key, gens)
        classes = []
        for a, c in enumerate(cls):
            gg = [_mat_geom(elems[i]) for i in c]
            det, turn, _pole_ = gg[0]
            classes.append(ClassInfo(a, len(c), det, turn, "general",
                                     [x[2] for x in gg], gg, [elems[i] for i in c]))
        has_i = any(mat_key(mat_neg(IDENTITY)) == mat_key(e) for e in elems)
        ctx = Ctx(name, "exceptional", elems, classes, has_i, None, len(elems))
    else:
        family, N = names.family_of(name)
        gens = _axial_generators(family, N)
        elems = _close(gens, lambda a, b: a * b, lambda g: g.key(), AX_E)
        cls = _conj_classes(elems, lambda a, b: a * b, lambda g: g.inv(),
                            lambda g: g.key(), gens)
        classes = []
        for a, c in enumerate(cls):
            gg = [_ax_geom(elems[i]) for i in c]
            det, turn, axis, _p = gg[0]
            classes.append(ClassInfo(a, len(c), det, turn, axis,
                                     [x[3] for x in gg], gg, [elems[i] for i in c]))
        ctx = Ctx(name, "axial", elems, classes, AX_I in elems, AX_SH in elems, len(elems))
    _CTX_CACHE[name] = ctx
    if ctx.has_sh is None:
        ctx.has_sh = any(lab.endswith("sigma_h") for lab in class_labels(name))
    return ctx


# ---------------------------------------------------------------- class symbols
def operation_symbol(det, turn):
    """(symbol, sort key) of the operation with determinant det and turn t = p/q in lowest
    terms: E, C_q^p, sigma_h (t = 0, det = -1), i (t = 1/2, det = -1), and S_q^j with j = p
    for odd p and j = p + q for even p."""
    t = F(turn) % 1
    p, q = t.numerator, t.denominator
    if det == 1:
        if q == 1:
            return ("E", (0, 0))
        return ("C_%d" % q if p == 1 else "C_%d^%d" % (q, p)), (q, p)
    if q == 1:
        return ("sigma_h", (0, 0))
    if q == 2 and p == 1:
        return ("i", (0, 0))
    j = p if p % 2 else p + q
    return ("S_%d" % q if j == 1 else "S_%d^%d" % (q, j)), (q, j)


def _axial_class_labels(ctx):
    """The class symbols of an axial group, in the order of ctx.classes: a principal-axis class
    takes the smallest symbol of its members; two classes of binary axes are C_2' (the one that
    holds the x axis) and C_2''; a single class is C_2' when C_2z is in the group, else C_2;
    two classes of vertical mirrors are sigma_v (the one through the x axis) and sigma_d; a
    single class is sigma_d when binary axes exist and none lies in its planes, else sigma_v."""
    cls = ctx.classes
    perp = [c.index for c in cls if c.axis == "perp"]
    mirr = [c.index for c in cls if c.axis == "mirror"]
    has_c2z = AxOp(0, F(1, 2), 1) in ctx.elements

    def holds_x(i):
        return any(p % 1 == 0 for p in cls[i].param)

    ptag, mtag = {}, {}
    if len(perp) == 2:
        a, b = perp
        if not holds_x(a):
            a, b = b, a
        ptag[a], ptag[b] = "'", "''"
    elif len(perp) == 1:
        ptag[perp[0]] = "'" if has_c2z else ""
    axang = {p for i in perp for p in cls[i].param}
    if len(mirr) == 2:
        a, b = mirr
        if not holds_x(a):
            a, b = b, a
        mtag[a], mtag[b] = "_v", "_d"
    elif len(mirr) == 1:
        i = mirr[0]
        contains = any(p in axang for p in cls[i].param)
        mtag[i] = "_d" if (axang and not contains) else "_v"

    out = []
    for c in cls:
        pre = "" if c.size == 1 else str(c.size)
        if c.axis == "z":
            cand = [operation_symbol(d, t) for (d, t, _a, _p) in c.reps]
            if any(s == "E" for s, _ in cand):
                out.append("E")
            elif any(s == "i" for s, _ in cand):
                out.append("i")
            elif any(s == "sigma_h" for s, _ in cand):
                out.append(pre + "sigma_h")
            else:
                out.append(pre + min(cand, key=lambda x: x[1])[0])
        elif c.axis == "perp":
            out.append(pre + "C_2" + ptag[c.index])
        else:
            out.append(pre + "sigma" + mtag[c.index])
    return out


def _exceptional_class_labels(ctx):
    """The class symbols of an exceptional group: the smallest symbol of the members, a mirror
    class being sigma_h when the normals of its planes lie along coordinate axes, sigma_d
    otherwise, and sigma in I and I_h."""
    icosahedral = ctx.name in ("I", "Ih")
    out = []
    for c in ctx.classes:
        pre = "" if c.size == 1 else str(c.size)
        cand = [operation_symbol(d, t) for (d, t, _p) in c.reps]
        syms = [s for s, _ in cand]
        if "E" in syms:
            out.append("E")
        elif "i" in syms:
            out.append("i")
        elif "sigma_h" in syms:
            if icosahedral:
                out.append(pre + "sigma")
            else:
                n_nonzero = sum(1 for x in c.reps[0][2] if not x.is_zero())
                out.append(pre + ("sigma_h" if n_nonzero == 1 else "sigma_d"))
        else:
            out.append(pre + min(cand, key=lambda x: x[1])[0])
    return out


def _order_key(ctx, c, lab):
    """The class order.  Axial: E; proper principal-axis classes by increasing angle; C_2' then
    C_2''; i; improper principal-axis classes by increasing angle; sigma_h; sigma_v; sigma_d.
    Exceptional: E; proper classes by decreasing element order, then increasing angle; i;
    improper classes likewise; the mirrors last, sigma_h first."""
    if ctx.kind == "axial":
        if lab == "E":
            return (0,)
        if lab == "i":
            return (3,)
        if c.axis == "z":
            return ((1 if c.det == 1 else 4), c.turn)
        if c.axis == "perp":
            return (2, 0 if lab.endswith("C_2'") else 1)
        return (5, 0 if lab.endswith("sigma_h") else (1 if lab.endswith("sigma_v") else 2))
    if lab == "E":
        return (0,)
    if lab == "i":
        return (2,)
    order = c.turn.denominator if c.det == 1 else F(c.turn + F(1, 2)).denominator
    if c.det == 1:
        return (1, -order, c.turn)
    if c.turn == 0:
        return (4, 0 if lab.endswith("sigma_h") else 1)
    return (3, -order, c.turn)


def class_labels(name):
    """The class labels (size prefix and symbol) of a group, in the class order."""
    ctx = context(name)
    if getattr(ctx, "_labels", None) is None:
        labs = (_axial_class_labels(ctx) if ctx.kind == "axial"
                else _exceptional_class_labels(ctx))
        order = sorted(range(len(labs)), key=lambda a: _order_key(ctx, ctx.classes[a], labs[a]))
        ctx._labels = [labs[a] for a in order]
        ctx._classes_ordered = [ctx.classes[a] for a in order]
    return list(ctx._labels)


def ordered_classes(name):
    """The classes (ClassInfo) of a group, in the class order."""
    class_labels(name)
    return context(name)._classes_ordered


