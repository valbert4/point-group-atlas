"""The finite point groups as exact sets of operations; their conjugacy classes, class symbols and
class order; the Mulliken labels of their irreps (CONVENTIONS.md sections 3, 5 and 6).

An axial group is built inside O(2) x {1, -1} with z the principal axis: the operation
AxOp(r, u, s) is, for r = 0, the rotation R_z(2 pi u) and, for r = 1, the reflection of the xy
plane in the line at azimuth pi u, followed by z -> s z.  So AxOp(1, u, -1) is the binary
rotation about the horizontal axis at azimuth pi u and AxOp(1, u, 1) the vertical mirror through
that axis.  An exceptional group is built from exact 3x3 matrices over Q(sqrt 5).
"""
from fractions import Fraction as F

from .. import names
