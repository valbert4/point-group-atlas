def _rotation_subgroup_name(name):
    """The name of G n SO(3) for a group with the inversion or sigma_h."""
    if names.kind_of(name) == "exceptional":
        return {"Th": "T", "Oh": "O", "Ih": "I", "Td": "T"}[name]
    family, N = names.family_of(name)
    rotation_family = {"Cnh": "Cn", "S2n": "Cn", "Dnh": "Dn", "Dnd": "Dn", "Cnv": "Cn"}
    return names.name_of(rotation_family[family], N)


def _z_classes(ctx):
    """(index, smallest positive turn, det) of every class of principal-axis operations."""
    out = []
    for j, c in enumerate(ordered_classes(ctx.name)):
        if c.axis != "z":
            continue
        ts = [t for (_d, t, _a, _p) in c.reps if t > 0]
        if ts:
            out.append((j, min(ts), c.det))
    return out


def _principal_generator_class(ctx):
    """(class index of g_p, M): g_p is the principal-axis operation of smallest positive angle
    1/M (a proper one before an improper one at the same angle)."""
    zc = _z_classes(ctx)
    if not zc:
        return None, 1
    tmin = min(t for (_j, t, _d) in zc)
    cands = [(j, d) for (j, t, d) in zc if t == tmin]
    cands.sort(key=lambda x: -x[1])
    return cands[0][0], tmin.denominator


def _flip_class(ctx, labs):
    """The class that fixes the subscript 1 or 2 of an axial group: C_2' when binary axes
    exist, else sigma_v."""
    cls = ordered_classes(ctx.name)
    perp = [j for j, c in enumerate(cls) if c.axis == "perp"]
    mirr = [j for j, c in enumerate(cls) if c.axis == "mirror"]

    def pick(S, wanted):
        if len(S) == 1:
            return S[0]
        return [j for j in S if labs[j].endswith(wanted) and not labs[j].endswith("'" + wanted)][0]

    if perp:
        return pick(perp, "C_2'")
    if mirr:
        return pick(mirr, "sigma_v")
    return None


def _rotation_restriction(ctx):
    """(context of H = G n SO(3), index map from the classes of H to the classes of G)."""
    hname = _rotation_subgroup_name(ctx.name)
    hctx = context(hname)
    keyf = mat_key if ctx.kind == "exceptional" else (lambda g: g.key())
    gmap = {}
    for j, c in enumerate(ordered_classes(ctx.name)):
        for e in c.members:
            gmap[keyf(e)] = j
    imap = [gmap[keyf(c.members[0])] for c in ordered_classes(hname)]
    return hctx, imap


def _sign_pm(x):
    s = real_sign(x)
    if s == 0:
        raise ArithmeticError("a character that fixes a label vanishes")
    return s


def _root_exponent(x, M):
    """q with x = zeta_M^q, or None."""
    for q in range(M):
        if x == Cyc.zeta(M, q):
            return q
    return None


def _two_cos_index(x, M):
    """q with x = 2 cos(2 pi q / M), 1 <= q <= M/2, or None."""
    for q in range(1, M // 2 + 1):
        if x == two_cos(M, q):
            return q
    return None


def _mulliken_struct(ctx, dim, chi):
    """(prefix, letter, subscript, kind of subscript, tag) of the irrep of dimension dim and
    characters chi (in the class order).  The tag g/u (the inversion present) or '/'' (sigma_h
    present, the inversion absent) is the sign of chi(i) or chi(sigma_h); the rest is the label
    of the restriction to G n SO(3).  In a rotation group: A or B by chi(g_p) = +1 or -1;
    1E_q (chi(g_p) = zeta_M^q, q < M/2) or 2E_q (its conjugate) for a complex character; E_q
    for chi(g_p) = 2 cos(2 pi q / M); subscript 1 or 2 of A and B by the sign of the character on
    the flip class; in the cubic and icosahedral groups 1E, 2E by the class 4C_3 and the
    subscript of A and T by the anchor class."""
    labs = class_labels(ctx.name)
    q_lab, tags = None, None
    if ctx.has_i:
        q_lab, tags = "i", ("g", "u")
    elif ctx.has_sh:
        q_lab, tags = "sigma_h", ("'", "''")
    if q_lab is not None:
        qi = (next(j for j, lab in enumerate(labs) if lab == "i" or lab.endswith("sigma_h"))
              if q_lab == "sigma_h" else labs.index("i"))
        hctx, imap = _rotation_restriction(ctx)
        pre, letter, sub, kind, _t = _mulliken_struct(hctx, dim, [chi[i] for i in imap])
        s = _sign_pm(chi[qi] * Cyc.rational(F(1, dim)))
        return (pre, letter, sub, kind, tags[0 if s > 0 else 1])

    if ctx.kind == "axial":
        gpi, M = _principal_generator_class(ctx)
        flip = _flip_class(ctx, labs)
        pre, sub, kind = "", None, None
        if dim == 1:
            x = chi[gpi] if gpi is not None else Cyc.one()
            if x == 1:
                letter = "A"
            elif x == -1:
                letter = "B"
            else:
                q = _root_exponent(x, M)
                letter, pre = "E", ("1" if 2 * q < M else "2")
                sub, kind = (q if 2 * q < M else M - q), "Eindex"
            if kind is None and flip is not None:
                s = _sign_pm(chi[flip])
                sub, kind = (1 if s > 0 else 2), "flip"
        else:
            q = _two_cos_index(chi[gpi], M)
            letter, sub, kind = "E", q, "Eindex"
        return (pre, letter, sub, kind, "")

    anchor = next((labs.index(a) for a in CUBIC_ANCHOR if a in labs), None)
    pre, sub, kind = "", None, None
    if dim == 1 and any(as_rational(x) is None for x in chi):
        q = _root_exponent(chi[_c3_class(ctx)], 3)
        return ("1" if 2 * q < 3 else "2", "E", None, None, "")
    letter = LETTER[dim]
    if anchor is not None and dim in (1, 3):
        sub, kind = (1 if _sign_pm(chi[anchor]) > 0 else 2), "anchor"
    return (pre, letter, sub, kind, "")


def _c3_class(ctx):
    """The class of the rotations by 1/3 turn about their poles."""
    for j, c in enumerate(ordered_classes(ctx.name)):
        ts = [t for (d, t, _p) in c.reps if d == 1 and t > 0]
        if ts and min(ts) == F(1, 3):
            return j


def _apply_alias(name, lab):
    tbl = SMALL_N_ALIAS.get(name)
    if not tbl:
        return lab
    pre, letter, sub, kind, tag = lab
    generic = "%s%s%s" % (pre, letter, ("_%s" % sub) if sub is not None else "")
    if generic in tbl:
        nl, ns = tbl[generic]
        return (pre, nl, ns, "alias", tag)
    return lab


def render_label(lab):
    pre, letter, sub, _kind, tag = lab
    if sub is not None:
        return "%s%s_%s%s" % (pre, letter, sub, tag)
    if tag in ("g", "u"):
        return "%s%s_%s" % (pre, letter, tag)
    return "%s%s%s" % (pre, letter, tag)


def mulliken(name, dim, chi):
    """The full Mulliken label (every subscript written) of the irrep with characters chi."""
    ctx = context(name)
    return render_label(_apply_alias(name, _mulliken_struct(ctx, int(dim), chi)))


def mulliken_table(name, irreps):
    """The short labels of all irreps [(dim, chi)] of a group: the E index is dropped when the
    group has a single E family, and the subscript 1 or 2 when no other irrep shares the
    letter and tag."""
    ctx = context(name)
    labs = [_apply_alias(name, _mulliken_struct(ctx, int(d), chi)) for d, chi in irreps]
    eidx = {lab[2] for lab in labs if lab[3] == "Eindex"}
    drop_e = len(eidx) <= 1
    keys = {}
    for lab in labs:
        if lab[3] in ("flip", "anchor"):
            keys.setdefault((lab[0], lab[1], lab[4]), []).append(lab)
    out = []
    for lab in labs:
        pre, letter, sub, kind, tag = lab
        if kind == "Eindex" and drop_e:
            sub = None
        if kind in ("flip", "anchor") and len(keys[(pre, letter, tag)]) == 1:
            sub = None
        out.append(render_label((pre, letter, sub, kind, tag)))
    return out
