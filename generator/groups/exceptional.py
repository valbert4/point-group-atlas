"""The irreducible characters of T, Th, Td, O, Oh, I, Ih.

The group, its classes and their order are those of groups.labels.  The characters are found in
Q(zeta_e), e the exponent of the group: the linear characters are the characters of the abelian
quotient G / [G, G]; the rest are split off, by the inner product
<a, b> = |G|^-1 sum_g a(g) conj(b(g)), from the character of the defining 3x3 representation,
the symmetric and antisymmetric squares (chi(g)^2 +- chi(g^2)) / 2, the Galois conjugates and the
products of the characters already found; there are as many irreducible characters as classes.
"""
import itertools
from fractions import Fraction as F
from math import gcd, lcm

from ..exact.cyclo import Cyc
from . import labels as L

# the exceptional groups that contain the inversion
CENTROSYMMETRIC = ("Th", "Oh", "Ih")


def element_order(A):
    n, P = 1, A
    one = L.mat_key(L.IDENTITY)
    while L.mat_key(P) != one:
        P = L.mat_mul(P, A)
        n += 1
    return n


def _closure(seeds):
    """The subgroup generated by `seeds`, as a dict key -> matrix."""
    out = {L.mat_key(L.IDENTITY): L.IDENTITY}
    frontier = [L.IDENTITY]
    while frontier:
        nxt = []
        for a in frontier:
            for s in seeds:
                p = L.mat_mul(a, s)
                k = L.mat_key(p)
                if k not in out:
                    out[k] = p
                    nxt.append(p)
        frontier = nxt
    return out


def derived_subgroup(gens):
    """[G, G]: the normal closure of the commutators of the generators."""
    seeds = []
    one = L.mat_key(L.IDENTITY)
    for a in gens:
        for b in gens:
            c = L.mat_mul(L.mat_mul(a, b), L.mat_mul(L.mat_inv(a), L.mat_inv(b)))
            if L.mat_key(c) != one and all(L.mat_key(c) != L.mat_key(s) for s in seeds):
                seeds.append(c)
    if not seeds:
        return {one: L.IDENTITY}
    while True:
        H = _closure(seeds)
        new = []
        for g in gens:
            for s in H.values():
                c = L.mat_mul(L.mat_mul(g, s), L.mat_inv(g))
                if L.mat_key(c) not in H:
                    new.append(c)
        if not new:
            return H
        seeds = seeds + new


def linear_characters(elems, idx, gens, classes, M):
    """The characters of G / [G, G], as tuples over the classes."""
    D = derived_subgroup(gens)
    n = len(elems)
    coset_of = [-1] * n
    reps = []
    for i, a in enumerate(elems):
        if coset_of[i] >= 0:
            continue
        c = len(reps)
        reps.append(a)
        for h in D.values():
            coset_of[idx[L.mat_key(L.mat_mul(a, h))]] = c
    nc = len(reps)

    def cmul(x, y):
        return coset_of[idx[L.mat_key(L.mat_mul(reps[x], reps[y]))]]

    e = coset_of[idx[L.mat_key(L.IDENTITY)]]
    agens = []
    span = {e}
    for x in range(nc):
        if x in span:
            continue
        agens.append(x)
        cur = set(span) | {x}
        changed = True
        while changed:
            changed = False
            for u in list(cur):
                for v in list(cur):
                    w = cmul(u, v)
                    if w not in cur:
                        cur.add(w)
                        changed = True
        span = cur
        if len(span) == nc:
            break

    def aorder(x):
        p, k = x, 1
        while p != e:
            p = cmul(p, x)
            k += 1
        return k

    ords = [aorder(g) for g in agens]
    one = Cyc(M, [1])
    chars = []
    for expo in itertools.product(*[range(o) for o in ords]):
        val = [None] * nc
        val[e] = one
        frontier = [e]
        ok = True
        while frontier and ok:
            nxt = []
            for u in frontier:
                for gi, g in enumerate(agens):
                    w = cmul(u, g)
                    v = val[u] * Cyc.zeta(M, expo[gi] * (M // ords[gi]))
                    if val[w] is None:
                        val[w] = v
                        nxt.append(w)
                    elif val[w] != v:
                        ok = False
                        break
                if not ok:
                    break
            frontier = nxt
        if ok and all(v is not None for v in val):
            chi = tuple(val[coset_of[idx[L.mat_key(c.members[0])]]] for c in classes)
            if chi not in chars:
                chars.append(chi)
    return chars


def _inner(order, sizes, a, b):
    """<a, b>, or None when it is not rational."""
    t = Cyc.zero()
    for s, x, y in zip(sizes, a, b):
        t = t + x * y.conjugate() * s
    t = t * F(1, order)
    return t.as_fraction() if t.is_rational() else None


def find_irreps(order, sizes, cls_e, linear, nat, powmap, M):
    """All irreducible characters, from the linear ones and the defining character `nat`."""
    nclasses = len(sizes)
    irreps = list(linear)

    def key(chi):
        return tuple(x.c for x in chi)

    def reduce_against(chi):
        r = list(chi)
        for psi in irreps:
            m = _inner(order, sizes, chi, psi)
            if m:
                r = [x - y * m for x, y in zip(r, psi)]
        return tuple(r)

    def try_add(chi):
        r = reduce_against(chi)
        if all(x.is_zero() for x in r):
            return False
        if _inner(order, sizes, r, r) != 1:
            return False
        if r[cls_e].c[0] < 0:
            r = tuple(-x for x in r)
        irreps.append(r)
        return True

    def sym_lam(chi, sign):
        return tuple((c * c + chi[powmap[a]] * sign) * F(1, 2) for a, c in enumerate(chi))

    pool = [nat]
    seen_pool = set()
    for _ in range(12):
        if len(irreps) == nclasses:
            break
        progressed = False
        for chi in list(pool):
            if key(chi) in seen_pool:
                continue
            seen_pool.add(key(chi))
            if try_add(chi):
                progressed = True
            if len(irreps) == nclasses:
                break
        if len(irreps) == nclasses:
            break
        newpool = []
        for a in irreps:
            newpool.append(sym_lam(a, 1))
            newpool.append(sym_lam(a, -1))
            for k in range(2, M):
                if gcd(k, M) == 1:
                    newpool.append(tuple(x.galois(k) for x in a))
            for b in irreps:
                newpool.append(tuple(x * y for x, y in zip(a, b)))
        pool = [p for p in newpool if key(p) not in seen_pool]
        if not pool and not progressed:
            break
    return irreps


def label_sort_key(lab):
    """(letter, prefix 1 or 2, numeric subscript) of a label such as "1E", "T_2", "A_1"."""
    pre = 0
    if lab and lab[0].isdigit():
        pre, lab = int(lab[0]), lab[1:]
    sub = 0
    if "_" in lab:
        digits = "".join(c for c in lab.split("_", 1)[1] if c.isdigit())
        sub = int(digits) if digits else 0
    return ("ABETGH".index(lab[0]), pre, sub)


def character_table(name):
    """{"order", "dims", "chi", "powmap"} of an exceptional group on the classes of
    labels.ordered_classes(name): chi[i][a] is the character of irrep i on class a, powmap[a] the
    class of the squares of class a.  The irreps are ordered by dimension and label for T, Td,
    O, I, and for Th, Oh, Ih by parity (g before u), then as the irreps of their rotation
    subgroup."""
    ctx = L.context(name)
    classes = L.ordered_classes(name)
    elems = ctx.elements
    idx = {L.mat_key(e): i for i, e in enumerate(elems)}
    cls_of = [None] * len(elems)
    for a, c in enumerate(classes):
        for m in c.members:
            cls_of[idx[L.mat_key(m)]] = a
    order = len(elems)
    sizes = [c.size for c in classes]
    cls_e = cls_of[idx[L.mat_key(L.IDENTITY)]]
    M = lcm(*(element_order(e) for e in elems))
    powmap = [cls_of[idx[L.mat_key(L.mat_mul(c.members[0], c.members[0]))]] for c in classes]
    nat = tuple(L.qs_to_cyc(L.mat_trace(c.members[0])) * Cyc(M, [1]) for c in classes)
    linear = linear_characters(elems, idx, L.EXCEPTIONAL_GENS[name], classes, M)
    rows = [[x.minimal() for x in r]
            for r in find_irreps(order, sizes, cls_e, linear, nat, powmap, M)]
    dims = [int(r[cls_e].as_fraction()) for r in rows]
    labels = [L.mulliken(name, d, r) for d, r in zip(dims, rows)]
    parity = [1 if lab.endswith("u") and name in CENTROSYMMETRIC else 0 for lab in labels]
    base = [lab[:-1].rstrip("_") if name in CENTROSYMMETRIC else lab for lab in labels]
    perm = sorted(range(len(rows)),
                  key=lambda i: (parity[i], dims[i], label_sort_key(base[i])))
    return {"order": order, "dims": [dims[i] for i in perm], "chi": [rows[i] for i in perm],
            "powmap": powmap}
